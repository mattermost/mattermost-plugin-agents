// fallbackModelsNote is appended to the system prompt when a request may be
// answered by a fallback model. It names models only: service names, URLs, and
// credentials stay out of the prompt.
const fallbackModelsNote = "If the primary model is unavailable, this response may be generated by one of these fallback models instead: %s. When asked which model you are, mention that a fallback model may be answering."

// allowedFallbackServiceIDs returns the prefix of primaryServiceID's fallback
// chain the user may use. Walks hops in order and stops at the first deny or
// evaluation error (later hops are not skipped). The primary is not included.
// A resolve error fails closed: callers must not attach the configured chain.
func (b *MMBots) allowedFallbackServiceIDs(ctx context.Context, userID, primaryServiceID string) ([]string, error) {
	chain, err := llm.ResolveFallbackChain(primaryServiceID, b.config.GetServiceByID)
	if err != nil {
		return nil, err
	}
	var ids []string
	for _, svc := range chain {
		if err := b.accessChecker.CanUseService(ctx, userID, svc.ID); err != nil {
			break
		}
		ids = append(ids, svc.ID)
	}
	return ids, nil
}

// fallbackAccessLLM stamps each user-attributed completion with the prefix of
// fallback service IDs the requesting user may use. Bifrost then attaches only
// that prefix so a denied hop is never attempted. It also tells the model
// which fallback models that prefix can reach.
type fallbackAccessLLM struct {
	inner            llm.LanguageModel
	bots             *MMBots
	primaryServiceID string
	primaryModel     string
	// fallbackServices is the chain the wrapped client was built with.
	fallbackServices []llm.ServiceConfig
}

func newFallbackAccessLLM(inner llm.LanguageModel, bots *MMBots, primaryServiceID, primaryModel string, fallbackServices []llm.ServiceConfig) llm.LanguageModel {
	return &fallbackAccessLLM{
		inner:            inner,
		bots:             bots,
		primaryServiceID: primaryServiceID,
		primaryModel:     primaryModel,
		fallbackServices: fallbackServices,
	}
}

func (w *fallbackAccessLLM) apply(ctx context.Context, request *llm.CompletionRequest) {
	w.restrict(ctx, request)
	w.describeFallbacks(request)
}

func (w *fallbackAccessLLM) restrict(ctx context.Context, request *llm.CompletionRequest) {
	if request.RestrictFallbacks {
		return
	}
	if request.Context == nil || request.Context.RequestingUser == nil || request.Context.RequestingUser.Id == "" {
		return
	}
	ids, err := w.bots.allowedFallbackServiceIDs(ctx, request.Context.RequestingUser.Id, w.primaryServiceID)
	request.RestrictFallbacks = true
	if err != nil {
		if w.bots.pluginAPI != nil {
			w.bots.pluginAPI.Log.Warn("Dropping fallbacks after chain resolution failed", "service_id", w.primaryServiceID, "error", err.Error())
		}
		return
	}
	request.AllowedFallbackServiceIDs = ids
}

// describeFallbacks appends the reachable fallback model names to the system
// post. The caller's posts are never modified.
func (w *fallbackAccessLLM) describeFallbacks(request *llm.CompletionRequest) {
	names := w.reachableFallbackModels(request)
	if len(names) == 0 {
		return
	}
	systemIdx := slices.IndexFunc(request.Posts, func(p llm.Post) bool { return p.Role == llm.PostRoleSystem })
	if systemIdx < 0 {
		return
	}
	request.Posts = slices.Clone(request.Posts)
	request.Posts[systemIdx].Message += "\n\n" + fmt.Sprintf(fallbackModelsNote, strings.Join(names, ", "))
}

// reachableFallbackModels mirrors how Bifrost attaches the chain: a
// restricted request stops at the first hop outside its allowed IDs, so a
// failed access lookup (restricted, no IDs) lists nothing.
func (w *fallbackAccessLLM) reachableFallbackModels(request *llm.CompletionRequest) []string {
	if len(w.fallbackServices) == 0 || !w.bots.licenseChecker.Allows(enterprise.CapModelFallback) {
		return nil
	}
	var allowed map[string]bool
	if request.RestrictFallbacks {
		allowed = make(map[string]bool, len(request.AllowedFallbackServiceIDs))
		for _, id := range request.AllowedFallbackServiceIDs {
			allowed[id] = true
		}
	}

	seen := map[string]bool{w.primaryModel: true}
	var names []string
	for _, svc := range w.fallbackServices {
		if allowed != nil && !allowed[svc.ID] {
			break
		}
		name := strings.TrimSpace(svc.DefaultModel)
		if name == "" || seen[name] {
			continue
		}
		seen[name] = true
		names = append(names, name)
	}
	return names
}

func (w *fallbackAccessLLM) ChatCompletion(ctx context.Context, request llm.CompletionRequest, opts ...llm.LanguageModelOption) (*llm.TextStreamResult, error) {
	w.apply(ctx, &request)
	return w.inner.ChatCompletion(ctx, request, opts...)
}

func (w *fallbackAccessLLM) ChatCompletionNoStream(ctx context.Context, request llm.CompletionRequest, opts ...llm.LanguageModelOption) (string, error) {
	w.apply(ctx, &request)
	return w.inner.ChatCompletionNoStream(ctx, request, opts...)
}

func (w *fallbackAccessLLM) CountTokens(ctx context.Context, request llm.CompletionRequest, opts ...llm.LanguageModelOption) (int, error) {
	w.apply(ctx, &request)
	return w.inner.CountTokens(ctx, request, opts...)
}

func (w *fallbackAccessLLM) InputTokenLimit() int {
	return w.inner.InputTokenLimit()
}

func (w *fallbackAccessLLM) OutputTokenLimit() int {
	return w.inner.OutputTokenLimit()
}
