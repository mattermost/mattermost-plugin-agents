// ErrAnalysisSourceUnavailable is returned when a thread or channel analysis
// is continued or regenerated by a user who can no longer read what it
// analyzed, or when that content, or the record of what it was, is gone.
var ErrAnalysisSourceUnavailable = errors.New("the analyzed content is no longer available to the requester")

// ErrToolCallingDisabled is returned when a tool decision would act on a run
// whose tools are disabled: channel tool calling is turned off, or the run
// was started by an automated invoker. The HTTP layer maps it to 403.
var ErrToolCallingDisabled = errors.New("tool calling is disabled for this conversation")

// turnRequest identifies a turn that is about to run: a new turn started by
// trigger, or a resume (regenerate, tool decision) of the run that produced
// post.
type turnRequest struct {
	bot     *bots.Bot
	user    *model.User
	channel *model.Channel
	// conv is the conversation the turn continues. New DM thread replies
	// leave it nil; the resolver looks it up.
	conv    *store.Conversation
	trigger *model.Post
	post    *model.Post
}

// turnPolicy is the resolved behavior of one turn. Every entry point that
// starts or resumes a turn gets it from resolveTurnPolicy, so gates, tool
// availability, and the auto-execute decision cannot drift between them.
type turnPolicy struct {
	c *Conversations
	turnRequest

	isDM         bool
	toolsEnabled bool
	// interactive means the requester is present to answer user-interaction
	// tools and connection requests.
	interactive bool
	// autoEverywhereOnly limits the catalog to tools that may run unattended
	// in a channel (auto_run_everywhere), for runs nobody is present to
	// approve.
	autoEverywhereOnly bool
}

// resolveTurnPolicy checks that req may run and derives how it runs. Gates
// fail closed: the requester's access to the agent, the channel license for
// every non-DM turn, and, for analysis conversations, the requester's access
// to the analyzed thread or channel.
func (c *Conversations) resolveTurnPolicy(ctx context.Context, req turnRequest) (*turnPolicy, error) {
	if req.bot == nil || req.user == nil || req.channel == nil {
		return nil, errors.New("turn is missing its agent, requester, or channel")
	}
	isDM := mmapi.IsDMWith(req.bot.GetMMBot().UserId, req.channel)

	if isDM {
		if err := c.bots.CheckUsageRestrictionsForUser(ctx, req.bot, req.user.Id); err != nil {
			return nil, err
		}
	} else {
		if err := c.bots.CheckUsageRestrictions(ctx, req.user.Id, req.bot, req.channel); err != nil {
			return nil, err
		}
		if err := c.licenseChecker.Check(enterprise.CapMultiplayerChannels); err != nil {
			return nil, err
		}
	}

	if req.conv == nil && isDM && req.trigger != nil && req.trigger.RootId != "" {
		if c.convService == nil {
			return nil, errors.New("conversation service not configured")
		}
		conv, err := c.convService.GetConversationByThread(req.trigger.RootId, req.bot.GetMMBot().UserId, req.user.Id)
		if err != nil {
			return nil, fmt.Errorf("failed to look up thread conversation: %w", err)
		}
		req.conv = conv
	}

	if err := c.checkAnalysisSource(req); err != nil {
		return nil, err
	}

	p := &turnPolicy{c: c, turnRequest: req, isDM: isDM}
	initiator, initiatingUser := req.trigger, req.user
	if req.trigger == nil {
		var err error
		if initiator, initiatingUser, err = c.runInitiator(req.conv, req.post); err != nil {
			return nil, err
		}
	}
	if isDM {
		p.toolsEnabled = true
		p.interactive = initiator != nil && initiatingUser != nil && !isAutomatedInvoker(initiator, initiatingUser)
	} else {
		p.setChannelRunTools(initiator, initiatingUser)
	}
	return p, nil
}

// activateTurnConversation restores the turn's conversation when it is
// archived (ActivateConversation leaves an active one unchanged). Every entry
// point that starts or resumes a turn on an existing conversation at the
// user's request calls it after resolveTurnPolicy accepts the turn, so a
// refused turn never un-archives, and the run continues on the restored row.
// Wakes never call it: they drop for an archived conversation instead.
func (c *Conversations) activateTurnConversation(p *turnPolicy) error {
	if p.conv == nil {
		return nil
	}
	conv, err := c.convService.ActivateConversation(p.conv)
	if err != nil {
		return fmt.Errorf("failed to restore archived conversation: %w", err)
	}
	p.conv = conv
	return nil
}

// setChannelRunTools derives tool availability for a channel run started by
// initiator, posted by initiatingUser. An unknown initiator is treated as
// unattended.
func (p *turnPolicy) setChannelRunTools(initiator *model.Post, initiatingUser *model.User) {
	configEnabled := p.c.channelMentionToolCallingEnabled()
	switch {
	case initiator == nil || initiatingUser == nil || isBotActivateAI(initiator, initiatingUser):
		p.toolsEnabled = configEnabled
		p.autoEverywhereOnly = configEnabled
	case isAutomatedInvoker(initiator, initiatingUser):
	default:
		p.toolsEnabled = configEnabled
		p.interactive = true
	}
}

// runInitiator returns the post that started the run which produced post,
// and its author. Both are nil when the run has no recorded initiating post or
// that post no longer exists; failing to look them up is an error.
func (c *Conversations) runInitiator(conv *store.Conversation, post *model.Post) (*model.Post, *model.User, error) {
	if conv == nil || post == nil {
		return nil, nil, nil
	}
	turn, err := c.convService.GetInitiatingUserTurn(conv.ID, post.Id)
	if err != nil {
		return nil, nil, fmt.Errorf("failed to look up the run's initiating turn: %w", err)
	}
	if turn == nil || turn.PostID == nil {
		return nil, nil, nil
	}
	initiator, err := c.mmClient.GetPost(*turn.PostID)
	if mmapi.IsNotFound(err) {
		return nil, nil, nil
	}
	if err != nil {
		return nil, nil, fmt.Errorf("failed to get the run's initiating post: %w", err)
	}
	initiatingUser, err := c.mmClient.GetUser(initiator.UserId)
	if err != nil {
		return nil, nil, fmt.Errorf("failed to get the run's initiating user: %w", err)
	}
	return initiator, initiatingUser, nil
}

// isAnalysisOperation reports whether conversations of operation replay
// content from the thread or channel they analyzed.
func isAnalysisOperation(operation string) bool {
	switch operation {
	case llm.OperationThreadAnalysis, llm.OperationChannelSummary, llm.OperationChannelInterval:
		return true
	}
	return false
}

// isAnalysisPost reports whether post is the response that started a thread
// or channel analysis.
func isAnalysisPost(post *model.Post) bool {
	if post == nil {
		return false
	}
	threadID, _ := post.GetProp(ThreadIDProp).(string)
	return threadID != "" || post.GetProp(AnalysisTypeProp) != nil || post.GetProp(AnalyzedChannelIDProp) != nil
}

// checkAnalysisSource re-checks that the requester can still read what an
// analysis analyzed before a turn that replays it runs. A source that is gone
// or unreadable denies with ErrAnalysisSourceUnavailable; failing to look it
// up is returned as is.
func (c *Conversations) checkAnalysisSource(req turnRequest) error {
	analysisPost, err := c.turnAnalysisPost(req)
	if err != nil || analysisPost == nil {
		return err
	}

	if threadID, _ := analysisPost.GetProp(ThreadIDProp).(string); threadID != "" {
		threadPost, err := c.getSourcePost(threadID)
		if err != nil {
			return fmt.Errorf("failed to get analyzed thread: %w", err)
		}
		return c.checkSourceChannel(req.user.Id, threadPost.ChannelId)
	}
	if channelID, _ := analysisPost.GetProp(AnalyzedChannelIDProp).(string); channelID != "" {
		return c.checkSourceChannel(req.user.Id, channelID)
	}
	return fmt.Errorf("analysis post records no analyzed thread or channel: %w", ErrAnalysisSourceUnavailable)
}

// turnAnalysisPost returns the analysis post whose source req replays, or nil
// when req continues no analysis. An analysis conversation is rooted at its
// analysis post; a legacy analysis post has no conversation. Analyses are
// posted as thread roots in the requester's DM with the agent, so any other
// turn in a DM thread (another agent mentioned there, or replies to a legacy
// analysis post, which continue an ordinary conversation) is checked against
// the thread root.
func (c *Conversations) turnAnalysisPost(req turnRequest) (*model.Post, error) {
	conv, post := req.conv, req.post
	if conv != nil && isAnalysisOperation(conv.Operation) {
		if conv.RootPostID == nil || *conv.RootPostID == "" {
			return nil, fmt.Errorf("analysis conversation has no analysis post: %w", ErrAnalysisSourceUnavailable)
		}
		if post != nil && post.Id == *conv.RootPostID {
			return post, nil
		}
		analysisPost, err := c.getSourcePost(*conv.RootPostID)
		if err != nil {
			return nil, fmt.Errorf("failed to get analysis post: %w", err)
		}
		return analysisPost, nil
	}
	if conv == nil && isAnalysisPost(post) {
		return post, nil
	}

	rootID := turnThreadRootID(req)
	if rootID == "" || req.channel.Type != model.ChannelTypeDirect {
		return nil, nil
	}
	root, err := c.getSourcePost(rootID)
	if err != nil {
		return nil, fmt.Errorf("failed to get thread root: %w", err)
	}
	if !isAnalysisPost(root) {
		return nil, nil
	}
	return root, nil
}

// turnThreadRootID returns the root of the thread req runs in, or "" when it
// is not in a thread.
func turnThreadRootID(req turnRequest) string {
	switch {
	case req.trigger != nil:
		return req.trigger.RootId
	case req.conv != nil && req.conv.RootPostID != nil:
		return *req.conv.RootPostID
	case req.post != nil:
		return req.post.RootId
	}
	return ""
}

// getSourcePost gets a post an analysis depends on. A post that no longer
// exists is reported as ErrAnalysisSourceUnavailable.
func (c *Conversations) getSourcePost(postID string) (*model.Post, error) {
	post, err := c.mmClient.GetPost(postID)
	if mmapi.IsNotFound(err) {
		return nil, fmt.Errorf("%w: %w", ErrAnalysisSourceUnavailable, err)
	}
	if err != nil {
		return nil, err
	}
	return post, nil
}

func (c *Conversations) checkSourceChannel(userID, channelID string) error {
	if !c.mmClient.HasPermissionToChannel(userID, channelID, model.PermissionReadChannel) {
		return ErrAnalysisSourceUnavailable
	}
	return nil
}

// buildContext builds the turn's LLM context with the tools the policy
// allows. extraOpts are applied after the policy's own options.
func (p *turnPolicy) buildContext(ctx context.Context, prefsLogMessage string, extraOpts ...llm.ContextOption) *llm.Context {
	builder := p.c.contextBuilder
	opts := []llm.ContextOption{builder.WithLLMContextResponseFiles()}
	if p.interactive {
		opts = append(opts, builder.WithLLMContextInteractive())
	}
	if p.autoEverywhereOnly {
		opts = append(opts, builder.WithLLMContextMCPToolFilter(func(tool llm.Tool) bool {
			return botChannelAutoEverywhereKeepTool(p.c.toolPolicyChecker, tool)
		}))
	}
	opts = append(opts, p.c.conversationToolOptions(p.bot, p.conv)...)
	opts = append(opts, extraOpts...)

	llmContext := p.c.buildConversationContextWithTools(ctx, p.bot, p.user, p.channel, prefsLogMessage, opts...)
	switch {
	case !p.toolsEnabled && !p.isDM && p.c.channelMentionToolCallingEnabled():
		// Tools are off only because nobody is present to approve them;
		// moving to a DM would not help, so the model is not told about them.
		llmContext.Tools.KeepToolsIf(func(llm.Tool) bool { return false })
	case !p.toolsEnabled:
		// Disabled tools stay listed so the model can point the user to a DM.
		llmContext.DisableTools(llmContext.Tools.GetToolsInfo()...)
	case p.autoEverywhereOnly:
		p.c.applyBotChannelAutoEverywhereToolFilter(llmContext)
	}
	return llmContext
}

// autoExecute decides, per tool call, whether the call runs without the
// requester's approval.
func (p *turnPolicy) autoExecute(llmCtx *llm.Context) func(llm.ToolCall) bool {
	return func(tc llm.ToolCall) bool {
		if !p.toolsEnabled {
			return false
		}
		if isMCPMetaToolCall(tc, llmCtx) {
			return true
		}
		var lookup llm.ToolLookup
		var found bool
		if llmCtx != nil {
			lookup, found = llmCtx.Tools.LookupTool(tc.Name, tc.ServerOrigin)
		}
		if !found {
			return false
		}
		if p.c.remoteMCPDecisionAllowed(lookup.ServerOrigin) != nil {
			return false
		}
		// Only honored for built-ins: an MCP tool carrying the flag must
		// still go through policy.
		if isAutoExecuteBuiltIn(lookup.Tool) {
			return true
		}
		policy, enabled := p.c.toolPolicyChecker.GetToolPolicy(lookup.ServerOrigin, lookup.BareName)
		if !enabled {
			return false
		}
		// The legacy auto_run policy is DM-only so a channel-visible reply
		// cannot reveal unshared tool output without an explicit Share.
		if p.isDM {
			return mcp.IsToolPolicyAutoRunInDM(policy)
		}
		return mcp.IsToolPolicyAutoRunEverywhere(policy)
	}
}

// remoteMCPDecisionAllowed returns ErrRemoteMCPNotLicensed when executing, or
// sharing the output of, a tool from serverOrigin needs the remote MCP
// license and the server does not have it. A nil license checker fails
// closed.
func (c *Conversations) remoteMCPDecisionAllowed(serverOrigin string) error {
	if mcp.IsRemoteServerOrigin(serverOrigin) && !c.licenseChecker.Allows(enterprise.CapRemoteMCP) {
		return ErrRemoteMCPNotLicensed
	}
	return nil
}

// sharedForTurns reports whether tool rounds the turn ran automatically may
// be written as shared, skipping the result-approval step. DM results are
// always shared; in a channel every call must be one the policy auto-runs
// there, which only auto_run_everywhere tools are.
func (p *turnPolicy) sharedForTurns(turns []toolrunner.ToolTurn, llmCtx *llm.Context) bool {
	if p.isDM {
		return true
	}
	autoExecute := p.autoExecute(llmCtx)
	sawToolCall := false
	for _, turn := range turns {
		for _, tc := range turn.AssistantToolCalls {
			sawToolCall = true
			if !autoExecute(tc) {
				return false
			}
		}
	}
	return sawToolCall
}

// runToolLoop runs the ToolRunner over req with the agent's round cap and the
// turn's auto-execute decision, persisting each intermediate tool round to
// convID as it completes. writeFailMsg (plus writeFailArgs) is logged when
// persisting a round fails.
func (p *turnPolicy) runToolLoop(ctx context.Context, llmCtx *llm.Context, convID string, req llm.CompletionRequest, writeFailMsg string, writeFailArgs ...any) (*toolrunner.ToolRunResult, error) {
	opts := p.c.withProviderWebSearchLicense(p.c.toolsDisabledLLMOptions(p.bot, !p.toolsEnabled))
	runner := toolrunner.New(p.bot.LLM(), toolrunner.WithMaxRounds(p.bot.GetConfig().EffectiveMaxToolTurns()), toolrunner.WithToolErrorResult(llmcontext.MCPToolErrorResult))
	return runner.Run(ctx, req, p.autoExecute(llmCtx), func(turns []toolrunner.ToolTurn) {
		if writeErr := p.c.convService.WriteToolTurns(convID, turns, p.sharedForTurns(turns, llmCtx)); writeErr != nil {
			p.c.mmClient.LogError(writeFailMsg, append([]any{"error", writeErr}, writeFailArgs...)...)
		}
	}, opts...)
}
